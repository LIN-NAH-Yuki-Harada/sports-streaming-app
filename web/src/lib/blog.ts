export function getPost(slug: string): Post | undefined {
  return POSTS.find((p) => p.slug === slug);
}

/** 新しい順（公開日の降順） */
export function getSortedPosts(): Post[] {
  return [...POSTS].sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}
